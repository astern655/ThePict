# --- 푸시업 측면 판정 경계 ------------------------------------------------
# 스쿼트용 0.35를 그대로 쓰면 정상 측면 푸시업 7편 중 2편을 '정면'으로 반려한다.
# 엎드린 자세에서는 몸통(어깨-엉덩이)이 화면상 짧게 투영돼 분모가 작아지고,
# 카메라가 조금만 높아도 두 어깨가 벌어져 보여 비율이 커지기 때문이다.
#
# 실측(비율 중앙값):
#   측면 16편  0.029 ~ 1.084 (사람이 눈으로 측면 전신임을 확인)
#   정면·사선 7편 0.235 ~ 3.027
# **두 분포가 거의 완전히 겹친다.** 경계를 0.35에 두면 정상 측면 16편 중 5편을,
# 0.70에서도 4편을 "정면이니 다시 촬영하라"고 반려한다. 스쿼트(선 자세)에서는
# 통했던 지표가 엎드린 자세에서는 판별력을 잃는다 — 몸통이 화면상 짧게 투영돼
# 분모가 작아지고, 카메라 높이가 조금만 달라도 두 어깨가 벌어져 보인다.
#
# 그래서 1.5로 낮춰 **정상 영상을 반려하지 않는 것**을 우선하고, 명백한 정면
# (1.778·3.027 같은 머리쪽 정면)만 걸러내는 약한 안전망으로만 남긴다.
# 제대로 고치려면 지표를 바꿔야 한다. docs/PUSHUP_TUNING.md §7-B
