#   - 그런데 로컬 영상에서는 s가 squat_003의 **최저점 프레임을 놓쳤다**(2.67초 →
#     3.50초로 밀림). 두 프레임을 육안 대조한 결과 2.67초가 명백히 더 깊고
#     3.50초는 이미 상승 중이었다. 그 여파로 무릎각 85°→99°, 거상각 23.5°→29.8°가
#     되어 정상 rep이 경계(30°)에 0.2°까지 붙었다.
#   - LLM-FMS는 최저점이 이미 주어진 단일 이미지라 **최저점 탐색 능력을 검증할 수
#     없다.** s의 이점은 '주어진 자세의 관절점 정확도'이고, 실제 제품 경로
#     (영상 → 최저점 탐색 → 판정)에서는 그 이점이 최저점 유실로 상쇄된다.
# 결론: 정적 벤치마크 점수보다 시계열 최저점 추적 안정성을 우선해 n을 유지한다.
# s 채택을 재검토하려면 최저점 추적이 개선됐는지를 먼저 영상으로 확인해야 한다.
#
# 비용: 두 운동을 모두 쓰는 서버는 가중치를 두 개 로드한다(각 ~10MB/20MB).
