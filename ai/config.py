"""AI 엔진 설정.

임계값·경로 같은 '숫자와 문자열'을 코드 곳곳에 흩뿌리지 않고 여기에 모은다.
튜닝할 때 이 파일만 보면 되도록 하는 것이 목적.
"""
from __future__ import annotations

from pathlib import Path

# --- 경로 ---------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = PROJECT_ROOT / "models"
DATA_DIR = PROJECT_ROOT / "data"
OUTPUT_DIR = DATA_DIR / "output"

for _d in (MODELS_DIR, DATA_DIR, OUTPUT_DIR):
    _d.mkdir(parents=True, exist_ok=True)

# --- 모델 ---------------------------------------------------------------
# n(nano) < s < m < l < x 순으로 무겁고 정확해짐. 처음엔 가벼운 n으로.
# 파일이 없으면 ultralytics가 최초 실행 시 자동 다운로드한다.
POSE_MODEL = "yolo11n-pose.pt"

# 관절 신뢰도가 이 값보다 낮으면 '못 본 것'으로 간주하고 계산에서 제외.
MIN_KEYPOINT_CONFIDENCE = 0.5

# --- 영상 메타데이터 위생 ------------------------------------------------
# 일부 컨테이너/변환 영상에서 OpenCV가 0이나 1000 같은 비정상 fps를 반환한다.
# 이 범위를 벗어나면 메타데이터를 신뢰하지 않고 대체값을 쓴다.
# (주의: 240fps 초과 슬로모션 원본을 직접 넣는 경우는 지원 범위 밖이다)
VIDEO_FPS_MIN = 1.0
VIDEO_FPS_MAX = 240.0
VIDEO_FPS_FALLBACK = 30.0

# --- 영상 품질 게이트 ----------------------------------------------------
# 처리한 프레임 중 사람이 검출된 비율이 이보다 낮으면 결과를 신뢰하기 어렵다.
# 리포트에 영상 수준 경고(low_detection)를 붙인다.
MIN_PERSON_RATIO = 0.5

# --- 측면 촬영 자동 검증 -------------------------------------------------
# 좌우 어깨의 화면상 수평 간격 ÷ 몸통 길이 비율. 측면이면 어깨가 겹쳐 작고(≤0.18),
# 정면이면 어깨너비만큼 벌어져 크다(≥0.35). docs/CAPTURE_AND_SQUAT_CRITERIA.md §5.
SIDE_VIEW_RATIO_MAX = 0.35   # 중앙값이 이보다 크면 '측면 촬영 아님'으로 판정
SIDE_VIEW_MIN_SAMPLES = 10   # 판정에 필요한 최소 표본 프레임 수(적으면 판단 보류)

# --- 스쿼트 반복 카운트 임계값 (도) --------------------------------------
# 히스테리시스: 내려감/올라옴 판정에 서로 다른 각을 써서 경계 떨림을 막는다.
SQUAT_KNEE_DOWN_ANGLE = 140.0   # 이보다 작아지면 '앉음(DOWN)'
SQUAT_KNEE_UP_ANGLE = 160.0     # 이보다 커지면 '일어섬(UP)'

# 무릎각 평활화(중앙값 필터) 윈도. 관절 좌표의 프레임 간 떨림으로 생기는
# 단발 스파이크를 제거해 rep 이중 카운트·최저점 오검출을 막는다. 1이면 비활성.
SQUAT_ANGLE_SMOOTH_WINDOW = 3

# 부분 반복(partial rep): 무릎각이 이 값 아래로 내려갔지만 DOWN 임계(140)까지는
# 못 간 채 다시 일어선 움직임. rep으로 세지 않되 별도로 집계해 안내한다.
# (UP·DOWN 임계의 중간값 — 서있을 때의 잔떨림은 부분 반복으로 치지 않기 위함)
SQUAT_PARTIAL_DIP_ANGLE = 150.0

# --- 스쿼트 자세 규칙 임계값 (측면 촬영 전용) ---------------------------
# 스쿼트 영상은 측면 촬영만 받는다(근거: docs/CAPTURE_AND_SQUAT_CRITERIA.md).
# 측면에서 정확히 측정 가능한 깊이·상체 앞숙임만 평가하며, 두 규칙 모두
# rep 최저점(가장 깊이 앉은 프레임)의 관절을 기준으로 판정한다.
#
# 두 규칙 모두 정도를 2단계로 나눈다. 기준선을 넘으면 '교정 권장'(WARNING),
# 심각 임계까지 넘으면 '명백한 결함'(ERROR)이며 rep 판정이 incorrect가 된다.
SQUAT_GOOD_DEPTH_ANGLE = 100.0     # 최저점 무릎각이 이보다 크면 깊이 부족 (WARNING)
SQUAT_SEVERE_DEPTH_ANGLE = 120.0   # 이보다도 크면 사실상 앉지 않은 것 (ERROR)

# 상체 앞숙임은 절대각이 아니라 '정강이 기울기와의 차이'(상체−정강이)로 판정한다.
# 깊게 앉을수록 정강이가 앞으로 기울고 상체도 그만큼 따라 기우는 것이 정상 균형이라,
# 절대각 기준은 깊고 올바른 스쿼트를 억울하게 처벌한다. docs …#4.3 참고.
# 25.0은 실영상 5개(rep 14개) 측정 분포에 맞춘 값이다. 정상 판정된 rep의 차이는
# 11.5° 이하에 몰렸고 22.6~28.7°에 또 한 덩어리가 있어, 그 사이 빈 구간에 기준선을
# 둔다. 20.0이던 시절에는 후자를 전부 걸어 오탐 4건(정밀도 0%)이 났다.
SQUAT_TORSO_SHIN_DIFF_WARN = 25.0    # 기울기 차가 이보다 크면 앞숙임 (WARNING)
SQUAT_TORSO_SHIN_DIFF_SEVERE = 35.0  # 이보다도 크면 굿모닝 자세 (ERROR)
SQUAT_TORSO_LEAN_HARD_MAX = 70.0     # 상체 절대 기울기가 이를 넘으면 정강이와 무관하게 ERROR
